import Foundation
import AppKit
import CoreGraphics
import ApplicationServices
import os
// OWNER: F1 (paste hardening). Decision logic (delays, pre-flight, restore guard, keycode order) is in PasteTarget.swift.
//
// paste(text, target:):
//   1. serialize: one paste at a time, held until the previous paste's clipboard restore finished
//   2. wait until the hotkey/modifiers are physically up (≤ 24 × 25 ms), then 30 ms
//   3. pre-flight: no AX trust / secure input / frontmost PID changed since key-up → copy only, return .copiedOnly
//      (not-editable AX role = warning only, still paste)
//   4. snapshot every pasteboard item × type → write text + Transient + AutoGenerated + private session marker →
//      wait for changeCount to commit (5 ms steps, ≤ 150 ms)
//   5. ⌘V (layout-aware keycode, .privateState source, 10 ms gaps, tagged eventSourceUserData) → if it could not be
//      posted: AX kAXSelectedTextAttribute → menu item bound to ⌘V (found by shortcut, not by English title) →
//      opt-in Unicode typing → clipboard + card. A paste that was posted is never retried (double paste).
//   6. in the background, after PasteDelays.restoreDelayMs(bundle id): restore the snapshot only if changeCount is
//      still ours AND our marker is still there; an empty clipboard before → cleared after. Then release the gate.
// Never logs the text.
public enum Paster {
    private struct Options: Sendable {
        var allowUnicodeTyping = false
        var restoreDelayOverrideMs: Int?
    }
    private static let options = OSAllocatedUnfairLock(initialState: Options())
    /// Developer-mode opt-in: last-resort per-character Unicode typing (breaks Cyrillic/Uzbek apostrophes in some apps).
    public static var allowUnicodeTyping: Bool {
        get { options.withLock { $0.allowUnicodeTyping } }
        set { options.withLock { $0.allowUnicodeTyping = newValue } }
    }
    /// Overrides the restore-delay table when set (paste-test --delay).
    public static var restoreDelayOverrideMs: Int? {
        get { options.withLock { $0.restoreDelayOverrideMs } }
        set { options.withLock { $0.restoreDelayOverrideMs = newValue } }
    }
    /// Written into `eventSourceUserData` of every event we post, so an event tap can recognise (and ignore) them.
    public static let syntheticEventTag: Int64 = 0x534F_594C_41   // "SOYLA"

    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let markerType = NSPasteboard.PasteboardType("ai.soyla.paste-session")
    private static let keyCommand: CGKeyCode = 0x37
    private static let gate = PasteGate()

    /// Insert `text` into `target` (the app frontmost at hotkey release). Never throws; never auto-retries.
    /// Returns as soon as the text is handed over; the clipboard restore finishes in the background
    /// (`awaitIdle()` waits for it; the next paste waits for it automatically).
    public static func paste(_ text: String, target: PasteTarget?, timeline: RunTimeline) async -> PasteOutcome {
        await gate.acquire()
        var releaseNow = true
        defer { if releaseNow { gate.release() } }

        await waitForKeysUp()
        let prepared = PasteText.prepare(text, bundleId: target?.bundleId)

        if let reason = PastePreflight.check(target: target) {
            copy(prepared, concealed: reason == .secureInput)
            Log.info("paste: not inserted (\(reason.rawValue)) — text left on the clipboard")
            return .copiedOnly(reason: reason)
        }
        let info = PastePreflight.focusedElementInfo()
        let editable = PastePreflight.looksEditable(role: info.role, settableValue: info.settableValue)
        if editable == false { Log.info("paste: focused element role \(info.role ?? "?") does not look editable — pasting anyway") }

        let pb = NSPasteboard.general
        let snapshot = takeSnapshot(pb)
        let token = UUID().uuidString
        let ours = await writeOurs(prepared, token: token, to: pb)

        let method: PasteMethod
        if await postCommandV(keyCode: PasteKeycode.current()) {
            method = .commandV
        } else if setSelectedTextViaAX(prepared) {
            method = .axSelectedText
        } else if pressPasteMenuItem(pid: target?.pid ?? PasteTarget.frontmostPID()) {
            method = .menuPaste
        } else if allowUnicodeTyping, await typeUnicode(prepared) {
            method = .unicodeTyping
        } else {
            Log.info("paste: every insertion method failed — text left on the clipboard")
            return .copiedOnly(reason: .postFailed)   // our text stays on the clipboard on purpose
        }
        timeline.mark(.pasted)

        let app = target?.pid.flatMap { NSRunningApplication(processIdentifier: $0) }
        let delay = restoreDelayOverrideMs
            ?? PasteDelays.restoreDelayMs(bundleId: target?.bundleId, isElectron: PasteDelays.bundleLooksChromium(app))
        releaseNow = false
        Task.detached {
            try? await Task.sleep(nanoseconds: UInt64(max(0, delay)) * 1_000_000)
            if RestoreGuard.shouldRestore(currentChangeCount: pb.changeCount, ourChangeCount: ours,
                                          markerToken: pb.string(forType: markerType), ourToken: token) {
                restore(pb, snapshot)
                timeline.mark(.clipboardRestored)
            } else {
                Log.info("paste: clipboard changed during the \(delay) ms window — kept the newer content")
            }
            gate.release()
        }
        return .pasted(method: method, targetLooksEditable: editable)
    }

    /// Wait until no paste or clipboard restore is in flight.
    public static func awaitIdle() async {
        await gate.acquire()
        gate.release()
    }

    /// Copy only (no ⌘V). Used by the panel's Copy button, pasteEnabled == false, and every not-inserted outcome.
    /// `concealed`: also mark it ConcealedType so clipboard managers don't keep it (text aimed at a secure field).
    public static func copy(_ text: String, concealed: Bool = false) {
        let pb = NSPasteboard.general
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for t in markerTypes(concealed: concealed) { item.setData(Data(), forType: t) }
        pb.writeObjects([item])
    }

    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static func markerTypes(concealed: Bool) -> [NSPasteboard.PasteboardType] { concealed ? [concealedType] : [] }

    /// The delay `paste` would use for this target (diagnostics / paste-test).
    public static func restoreDelayMs(for target: PasteTarget?) -> Int {
        let app = target?.pid.flatMap { NSRunningApplication(processIdentifier: $0) }
        return restoreDelayOverrideMs
            ?? PasteDelays.restoreDelayMs(bundleId: target?.bundleId, isElectron: PasteDelays.bundleLooksChromium(app))
    }

    // MARK: - steps

    /// Hotkey modifiers still physically down would turn ⌘V into ⌥⌘V / fn⌘V etc. Poll ≤ 24 × 25 ms, then 30 ms.
    static func waitForKeysUp() async {
        let mods: CGEventFlags = [.maskCommand, .maskAlternate, .maskControl, .maskShift, .maskSecondaryFn]
        for _ in 0..<24 {
            if CGEventSource.flagsState(.hidSystemState).intersection(mods).isEmpty { break }
            try? await Task.sleep(nanoseconds: 25_000_000)
        }
        try? await Task.sleep(nanoseconds: 30_000_000)
    }

    typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    private static func takeSnapshot(_ pb: NSPasteboard) -> Snapshot {
        (pb.pasteboardItems ?? []).map { item in
            item.types.compactMap { t in item.data(forType: t).map { (t, $0) } }
        }
    }

    /// Write text + Transient + AutoGenerated + marker; wait (5 ms steps, ≤ 150 ms) until changeCount moved.
    private static func writeOurs(_ text: String, token: String, to pb: NSPasteboard) async -> Int {
        let before = pb.changeCount
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        item.setString(token, forType: markerType)
        pb.writeObjects([item])
        for _ in 0..<30 where pb.changeCount == before {
            try? await Task.sleep(nanoseconds: 5_000_000)
        }
        return pb.changeCount
    }

    private static func restore(_ pb: NSPasteboard, _ snapshot: Snapshot) {
        pb.clearContents()   // empty clipboard before → empty after
        let items: [NSPasteboardItem] = snapshot.compactMap { pairs in
            guard !pairs.isEmpty else { return nil }
            let it = NSPasteboardItem()
            for (t, d) in pairs { it.setData(d, forType: t) }
            return it
        }
        if !items.isEmpty { pb.writeObjects(items) }
    }

    /// ⌘ down, V down, V up, ⌘ up from a private-state source (held hotkey modifiers don't leak in), 10 ms apart.
    private static func postCommandV(keyCode: CGKeyCode) async -> Bool {
        guard let src = CGEventSource(stateID: .privateState) else { return false }
        src.userData = syntheticEventTag
        let specs: [(CGKeyCode, Bool, CGEventFlags)] = [
            (keyCommand, true, .maskCommand), (keyCode, true, .maskCommand),
            (keyCode, false, .maskCommand), (keyCommand, false, []),
        ]
        var events: [CGEvent] = []
        for (k, down, flags) in specs {
            guard let e = CGEvent(keyboardEventSource: src, virtualKey: k, keyDown: down) else { return false }
            e.flags = flags
            e.setIntegerValueField(.eventSourceUserData, value: syntheticEventTag)
            events.append(e)
        }
        for (i, e) in events.enumerated() {
            if i > 0 { try? await Task.sleep(nanoseconds: 10_000_000) }
            e.post(tap: .cghidEventTap)
        }
        return true
    }

    /// AX fallback: replace the focused element's selection with the text.
    private static func setSelectedTextViaAX(_ text: String) -> Bool {
        guard let el = PastePreflight.focusedElement() else { return false }
        return AXUIElementSetAttributeValue(el, kAXSelectedTextAttribute as CFString, text as CFString) == .success
    }

    /// Press the target app's menu item whose shortcut is plain ⌘V (works in any UI language).
    private static func pressPasteMenuItem(pid: pid_t?) -> Bool {
        guard let pid else { return false }
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, 0.5)
        guard let bar = axElement(app, kAXMenuBarAttribute) else { return false }
        for top in axChildren(bar).dropFirst() {          // skip the Apple menu
            for menu in axChildren(top) {
                for item in axChildren(menu) {
                    var ch: CFTypeRef?, mods: CFTypeRef?, en: CFTypeRef?
                    guard AXUIElementCopyAttributeValue(item, kAXMenuItemCmdCharAttribute as CFString, &ch) == .success,
                          (ch as? String)?.uppercased() == "V" else { continue }
                    AXUIElementCopyAttributeValue(item, kAXMenuItemCmdModifiersAttribute as CFString, &mods)
                    guard (mods as? Int ?? 0) == 0 else { continue }   // 0 = ⌘ only
                    AXUIElementCopyAttributeValue(item, kAXEnabledAttribute as CFString, &en)
                    guard (en as? Bool) != false else { continue }
                    return AXUIElementPerformAction(item, kAXPressAction as CFString) == .success
                }
            }
        }
        return false
    }

    private static func axElement(_ el: AXUIElement, _ attr: String) -> AXUIElement? {
        var ref: CFTypeRef?
        guard AXUIElementCopyAttributeValue(el, attr as CFString, &ref) == .success, let r = ref,
              CFGetTypeID(r) == AXUIElementGetTypeID() else { return nil }
        return (r as! AXUIElement)
    }

    private static func axChildren(_ el: AXUIElement) -> [AXUIElement] {
        var ref: CFTypeRef?
        guard AXUIElementCopyAttributeValue(el, kAXChildrenAttribute as CFString, &ref) == .success else { return [] }
        return (ref as? [AXUIElement]) ?? []
    }

    /// Opt-in only: post the text as Unicode keyboard events in 20-UTF-16-unit chunks.
    private static func typeUnicode(_ text: String) async -> Bool {
        guard let src = CGEventSource(stateID: .privateState) else { return false }
        src.userData = syntheticEventTag
        var units = Array(text.utf16)[...]
        while !units.isEmpty {
            var n = min(20, units.count)
            // don't split a surrogate pair
            if n < units.count, UTF16.isLeadSurrogate(units[units.startIndex + n - 1]) { n -= 1 }
            let chunk = Array(units.prefix(n))
            units = units.dropFirst(n)
            for down in [true, false] {
                guard let e = CGEvent(keyboardEventSource: src, virtualKey: 0, keyDown: down) else { return false }
                e.flags = []
                e.setIntegerValueField(.eventSourceUserData, value: syntheticEventTag)
                chunk.withUnsafeBufferPointer { e.keyboardSetUnicodeString(stringLength: n, unicodeString: $0.baseAddress) }
                e.post(tap: .cghidEventTap)
            }
            try? await Task.sleep(nanoseconds: 5_000_000)
        }
        return true
    }
}

/// FIFO async mutex: one paste (including its clipboard restore) at a time.
final class PasteGate: Sendable {
    private struct State: Sendable {
        var held = false
        var waiters: [CheckedContinuation<Void, Never>] = []
    }
    private let state = OSAllocatedUnfairLock(initialState: State())

    func acquire() async {
        await withCheckedContinuation { (c: CheckedContinuation<Void, Never>) in
            let acquired = state.withLock { s -> Bool in
                if !s.held { s.held = true; return true }
                s.waiters.append(c); return false
            }
            if acquired { c.resume() }   // resumed outside the lock, as before
        }
    }

    func release() {
        let next = state.withLock { s -> CheckedContinuation<Void, Never>? in
            if s.waiters.isEmpty { s.held = false; return nil }
            return s.waiters.removeFirst()
        }
        next?.resume()
    }
}
